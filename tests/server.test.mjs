import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtempSync,rmSync,readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
const temp=mkdtempSync(path.join(tmpdir(),'fw-test-'));
const child=spawn(process.execPath,['server.mjs'],{env:{...process.env,PORT:'0',HOST:'127.0.0.1',DATA_DIR:temp},stdio:['ignore','pipe','inherit']});
let base;
const started=new Promise((resolve,reject)=>{child.stdout.on('data',chunk=>{const match=chunk.toString().match(/http:\/\/localhost:(\d+)/);if(match){base=`http://127.0.0.1:${match[1]}`;resolve();}});child.once('error',reject);child.once('exit',code=>{if(!base)reject(new Error(`Server exited ${code}`));});});
const places=[{id:'a',name:'面馆',price:26,category:'面食'},{id:'b',name:'火锅',price:80,category:'火锅'},{id:'c',name:'家常菜',price:38,category:'家常菜'}];
async function req(route,body,token){const res=await fetch(base+'/api'+route,{method:body===undefined?'GET':'POST',headers:{'Content-Type':'application/json',...(token?{'x-member-token':token}:{})},...(body===undefined?{}:{body:JSON.stringify(body)})});return {status:res.status,data:await res.json()};}
test('双设备完整流程、权限、隐私、异议与持久化',async t=>{
 await started;
 t.after(()=>{child.kill();rmSync(temp,{recursive:true,force:true});});
 let created=await req('/rooms',{title:'测试午餐',name:'甲',places});assert.equal(created.status,201);
 const code=created.data.room.code,host=created.data.token;let r=created.data.room;
 const joined=await req(`/rooms/${code}/join`,{name:'乙'});assert.equal(joined.status,200);const guest=joined.data.token;
 const act=async(a,b,token)=>{const fresh=await req(`/rooms/${code}`,undefined,token);return req(`/rooms/${code}/${a}`,{...b,revision:fresh.data.revision},token);};
 assert.equal((await req(`/rooms/${code}`)).status,401);
 assert.equal((await act('spin',{},host)).status,400);
 let p=await act('preferences',{preferences:{budget:100,excluded:[],categories:[]}},host);assert.equal(p.status,200);
 p=await act('preferences',{preferences:{budget:40,excluded:[],categories:[]}},guest);assert.equal(p.data.stage,'candidates');assert.equal(p.data.candidates.length,2);
 assert.ok(p.data.members.every(m=>!('token'in m)&&!('prefs'in m)));assert.equal(p.data.me.prefs.budget,40);
 assert.equal((await act('spin',{},host)).status,400);
 const beforeApprove=(await req(`/rooms/${code}`,undefined,host)).data;
 await act('approve',{},host);
 const concurrentApprove=await req(`/rooms/${code}/approve`,{revision:beforeApprove.revision,round:beforeApprove.round},guest);assert.equal(concurrentApprove.status,200);assert.equal(concurrentApprove.data.canSpin,true);
 assert.equal((await act('spin',{},guest)).status,403);
 r=(await act('spin',{},host)).data;assert.equal(r.stage,'result');assert.ok(r.result.price<=40);
 assert.equal((await req(`/rooms/${code}/join`,{name:'迟到'})).status,400);
 let rejected=await act('reject',{reason:'今天不合适'},guest);assert.equal(rejected.data.stage,'candidates');assert.equal(rejected.data.rejected.length,1);assert.ok(rejected.data.members.every(m=>!m.approved&&!m.confirmed));
 const stale=rejected.data.revision;await act('approve',{},host);assert.equal((await req(`/rooms/${code}/approve`,{revision:stale},guest)).status,409);
 await act('approve',{},guest);r=(await act('spin',{},host)).data;assert.equal(r.candidates.length,1);
 await new Promise(resolve=>setTimeout(resolve,2850));
 r=(await act('confirm',{},host)).data;assert.equal(r.stage,'result');r=(await act('confirm',{},guest)).data;assert.equal(r.stage,'done');assert.ok(r.completedAt);
 assert.equal((await act('feedback',{value:'went'},guest)).status,403);
 r=(await act('feedback',{value:'went'},host)).data;assert.equal(r.feedback.value,'went');
 const stored=JSON.parse(readFileSync(path.join(temp,'food-wheel.json')));assert.equal(stored.rooms[code].stage,'done');assert.ok(stored.events.some(e=>e.type==='decision_completed'));assert.ok(stored.events.some(e=>e.type==='meal_feedback'));
 assert.equal((await req('/rooms',{places:[]})).status,400);
});
